import { Router } from 'express';
import { createSupportTicket, finishStudySession, getAdminUsers, getAssignments, getCourseEnrollments, getCurrentProfile, getDashboard, getEnrolledCourses, getQuizDetails, getQuizzes, getStudentDirectory, getSupportTickets, patchSubmissionGrade, postAssignment, postAssignmentSubmission, postCourse, postEnrollment, postQuiz, postQuizAttempt, postStudySession, submitQuiz, updateUserRole } from '../controllers/apiController.js';
import { requireAuth, requireRole } from '../middleware/auth.js';
import { validateBody } from '../middleware/validateBody.js';
import { assignmentSchema, courseSchema, enrollmentSchema, gradeSchema, quizAnswersSchema, quizSchema, roleSchema, studySessionSchema, submissionSchema, ticketSchema } from '../validators/apiSchemas.js';

const router = Router();
router.get('/me', requireAuth, getCurrentProfile);
router.get('/dashboard', requireAuth, getDashboard);
router.post('/study-sessions', requireAuth, requireRole('student'), validateBody(studySessionSchema), postStudySession);
router.patch('/study-sessions/:sessionId/finish', requireAuth, requireRole('student'), finishStudySession);
router.get('/courses', requireAuth, getEnrolledCourses);
router.get('/assignments', requireAuth, getAssignments);
router.post('/assignments', requireAuth, requireRole('teacher', 'admin'), validateBody(assignmentSchema), postAssignment);
router.post('/assignments/:assignmentId/submissions', requireAuth, validateBody(submissionSchema), postAssignmentSubmission);
router.patch('/submissions/:submissionId/grade', requireAuth, requireRole('teacher', 'admin'), validateBody(gradeSchema), patchSubmissionGrade);
router.get('/quizzes', requireAuth, getQuizzes);
router.get('/quizzes/:quizId', requireAuth, getQuizDetails);
router.post('/quizzes', requireAuth, requireRole('teacher', 'admin'), validateBody(quizSchema), postQuiz);
router.post('/quizzes/:quizId/attempts', requireAuth, postQuizAttempt);
router.post('/quiz-attempts/:attemptId/submit', requireAuth, validateBody(quizAnswersSchema), submitQuiz);
router.get('/support/tickets', requireAuth, getSupportTickets);
router.post('/courses', requireAuth, requireRole('teacher', 'admin'), validateBody(courseSchema), postCourse);
router.get('/courses/:courseId/enrollments', requireAuth, requireRole('teacher', 'admin'), getCourseEnrollments);
router.post('/courses/:courseId/enrollments', requireAuth, requireRole('teacher', 'admin'), validateBody(enrollmentSchema), postEnrollment);
router.get('/admin/users', requireAuth, requireRole('admin'), getAdminUsers);
router.get('/students', requireAuth, requireRole('admin'), getStudentDirectory);
router.patch('/admin/users/:id/role', requireAuth, requireRole('admin'), validateBody(roleSchema), updateUserRole);
router.post('/support/tickets', requireAuth, validateBody(ticketSchema), createSupportTicket);
export default router;
